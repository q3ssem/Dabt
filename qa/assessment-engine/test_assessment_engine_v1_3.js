const assert=require('node:assert/strict');
const E=require('./Dabt_Assessment_Engine_v1.3.js');
const responses=[{trial:1,ok:true,rt:500,target:'A',value:'A'},{trial:2,ok:false,rt:900,target:'B',value:'A'},{trial:3,ok:true,rt:700,target:'C',value:'C'},{trial:4,ok:true,rt:600,target:'D',value:'D'}];
const t=E.scoreSession({sessionId:'t1',gameId:'rule-switch',domainId:'cognitive-flexibility',mode:'training',responses});
const a=E.scoreSession({sessionId:'a1',gameId:'rule-switch',domainId:'cognitive-flexibility',mode:'assessment',responses});
assert.equal(t.accuracy,.75); assert.equal(t.responseTime.medianMs,650); assert.equal(t.mode,'training');
assert.equal(E.validResult(t),true);
assert.throws(()=>E.scoreSession({responses:[{ok:'false'}]}));
assert.throws(()=>E.scoreSession({domainId:'made-up',responses}));
assert.throws(()=>E.scoreSession({mode:'other',responses}));
assert.throws(()=>E.scoreSession({responses:[{ok:true,rt:-2}]}));
assert.throws(()=>E.scoreSession({passThreshold:2,responses}));
const prog=E.scoreProgram({sequenceId:'run1',gameId:'rule-switch',mode:'assessment',stages:[{domainId:'reasoning',responses},{domainId:'visuospatial',responses}]});
assert.equal(prog.stageCount,2); assert.equal(prog.stages[0].stageIndex,1); assert.equal(prog.stages[1].sequenceId,'run1'); assert.equal(prog.accuracy,.75);
class MemoryStorage{constructor(){this.data={};}getItem(k){return this.data[k]??null;}setItem(k,v){this.data[k]=v;}removeItem(k){delete this.data[k];}}
const store=E.createStore(new MemoryStorage());
assert.equal(store.add(t).added,true); assert.equal(store.add(t).reason,'duplicate-session');
assert.equal(store.addProgram(prog).added,2); assert.equal(store.getAll().length,3);
const summary=E.summarize(store.getAll()); assert.equal(summary.byMode.training.sessions,1); assert.equal(summary.byMode.assessment.sessions,2);
assert.equal(summary.byMode.assessment.attemptWeightedAccuracy,.75);
const dash=E.dashboard(store.getAll()); assert.equal(dash.totals.sessions,3); assert.equal(dash.domainSnapshot.length,2);
assert.equal(dash.trendByDomain.reasoning.length,1); assert.equal(dash.recentSessions.length,3);
const backup=store.exportData(),restore=E.createStore(new MemoryStorage());
assert.equal(restore.importData(backup).added,3); assert.equal(restore.getAll().length,3);
assert.equal(restore.importData(backup).duplicates,3); restore.clear(); assert.equal(restore.getAll().length,0);
const imported=E.validateImport({schemaVersion:3,results:[t,t,{...a,accuracy:2},{...a,correct:9}]});
assert.equal(imported.results.length,1); assert.equal(imported.rejected.length,3);
assert.throws(()=>E.validateImport({schemaVersion:999,results:[]}));
const broken=E.createStore(new MemoryStorage()); broken.add(t);
const payload=broken.exportData(); payload.results[0].errors=0;
assert.equal(E.validateImport(payload).rejected.length,1);
const quota={getItem(){return null;},setItem(){throw new Error('quota exceeded');},removeItem(){}};
assert.throws(()=>E.createStore(quota).add(t),/Unable to save/);
console.log('PASS: strict input validation, scoring, multi-stage programs, weighted aggregates, dashboard trends, local persistence, backup/restore, migration validation, duplicate handling, quota errors');