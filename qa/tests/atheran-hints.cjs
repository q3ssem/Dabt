'use strict';
const fs = require('node:fs');
const assert = require('node:assert/strict');
const html = fs.readFileSync('index.html', 'utf8');
let checks = 0;
const ok = (value, label) => { assert.ok(value, label); checks++; };
const block = (name) => {
  const start = html.indexOf(`function ${name}(){`);
  assert.ok(start >= 0, `function exists: ${name}`);
  const candidates = ['\n/* =================', '\n/* ----------', '\nconst PZ_'];
  const ends = candidates.map(x => html.indexOf(x, start + 10)).filter(x => x > start);
  return html.slice(start, Math.min(...ends));
};

const port = block('runAPort');
ok(port.includes('P.need.indexOf(Math.max(...P.need))'), 'tide hint chooses the most demanding passage');
ok(port.includes('P.h[P.t0+i]'), 'tide hint uses the generated water height at the matching passage');
const light = block('runALight');
ok(light.includes('P.runs.slice().sort((a,b)=>b[1]-a[1])'), 'lighthouse hint ranks distinctive pattern runs');
ok(light.includes('runs[1]'), 'lighthouse third hint advances beyond the longest run');
const shade = block('runAShade');
ok(shade.includes('الصف ${XAR(y+1)} والعمود ${XAR(x+1)}'), 'shadow hint ends with exact row and column');
const swarm = block('runASwarm');
ok(swarm.includes('P.ty.slice(b*C,(b+1)*C)'), 'white-swarm hint ranks constrained rows');
ok(swarm.includes('k%C===b'), 'white-swarm hint ranks constrained columns');
ok(!swarm.includes('const i=rnd(R)') && !swarm.includes('const j=rnd(C)'), 'white-swarm hints no longer choose random rows or columns');
const echo = block('runAEcho');
ok(echo.includes('aecCandidateCells(P,[i]).length'), 'echo hint counts candidates against each listener distance');
ok(echo.includes('const best=counts[0]'), 'echo hint selects the most discriminating listener');
ok(echo.includes('الصف ${XAR(y+1)} والعمود ${XAR(x+1)}'), 'echo final hint gives both coordinates');
const song = block('runAVsong');
ok(song.includes('ops[0]') && song.includes('ops[1]'), 'echo-song rule is revealed one operation at a time');
const giant = block('runAGiant');
ok(giant.includes('الصف ${XAR(y+1)}') && giant.includes('العمود ${XAR(x+1)}'), 'giant prediction hint gives row and column');
const silent = block('runASilent');
ok(silent.includes('id="asireplay"'), 'silent observation has a replay control');
ok(silent.includes('function playScene(replay=false)'), 'silent scene playback can be replayed');
ok(silent.includes('playScene(true)'), 'second hint replays the observation');
ok(silent.includes('P.qs[qi]'), 'final silent hint refers to the active question, not a future one');
const city = block('runACity');
ok(city.includes('actAlive(P,i)') && city.includes('b.d-a.d'), 'living-city exclusion hint ranks alternatives by causal mismatch');
const deep = block('runASong');
ok(deep.includes('P.sp[i].slice(1).map'), 'deep-song hint exposes interval fingerprint');
const flow = block('runAFlow');
ok(flow.includes('const flow=a=>'), 'current-fork hint derives flow through the actual graph');
ok(flow.includes('(j.v)') && flow.includes('ليس الأهدأ'), 'current-fork third hint reveals one competing bay, not all results (5.5.28: with Arabic number agreement)');
const heart = block('runAHeart');
ok(heart.includes('const last=nextOp()'), 'Atheran heart hint references the next operation to reverse');
ok(heart.includes('opTxt({...last,k:-last.k})'), 'Atheran heart hint gives the inverse of the next operation');
const spore = block('runWSpore');
ok(spore.includes('const wrong=u.findIndex'), 'spore hint identifies an incorrect selection before replacing it');
ok(spore.includes('u[i]=1') && spore.includes('draw()'), 'spore hint adds a correct selection and redraws');
ok(!spore.includes('u.fill(0)'), 'spore hint never wipes all prior selections');
const log = block('runWLog');
ok(log.includes('const abs=P.pages[n].abs'), 'ship-log hint derives the next page date');
ok(log.includes('if(k===2)return`الصفحة'), 'ship-log second hint reveals the date without changing order');
const lake = block('runWLake');
ok(lake.includes('sel=P.ans;draw();return`حددت الكوكبة المطابقة'), 'sky-lake final hint marks the correct option');
ok(lake.includes('استبعد الكوكبة رقم'), 'sky-lake second hint only excludes a decoy');
const sw = fs.readFileSync('sw.js', 'utf8');
ok(sw.includes("const VERSION='5.5.29'"), 'hint release cache is versioned 5.5.28');
console.log(`Atheran progressive hints: ${checks} assertions passed; 15 puzzle experiences audited.`);
