const assert=require('assert');
require('../../expedition10/logic.js');
const L=global.ML10Logic,A=L.audit();
assert.deepStrictEqual(A.manifestSolutions,[['بلور','بوصلة','لؤلؤ','توابل']],'cargo manifest must have exactly one valid arrangement');
assert(L.manifestValid(['بلور','بوصلة','لؤلؤ','توابل']),'designed cargo arrangement is valid');
assert(!L.manifestValid(['لؤلؤ','بوصلة','بلور','توابل']),'an invalid manifest is rejected');
assert.deepStrictEqual(A.tideSolutions,[[2,5,1]],'tidal clues must produce one three-sector sequence');
assert.strictEqual(L.tideSectorCount,8,'tidal wheel contains eight sectors');
assert.deepStrictEqual(L.tideTargets,[2,5,1],'timing sequence matches the clue-derived targets');
assert.strictEqual(A.relic.distance,8,'relic sliding puzzle has an eight-move shortest solution');
assert.strictEqual(A.relic.count,1,'relic sliding puzzle has a unique shortest solution');
assert.deepStrictEqual(A.relic.path,['up','up','left','left','down','down','right','right'],'relic solver returns the published solution');
assert.strictEqual(A.crate.pushes,6,'captain crate puzzle has a six-push shortest solution');
assert.strictEqual(A.crate.count,1,'captain crate puzzle has one shortest push sequence');
assert.deepStrictEqual(A.crate.path,['up','up','up','up','right','right'],'crate solver returns the published push sequence');
assert.strictEqual(A.knight.unique,true,'guardian knight board is an induced path with no shortcut');
assert.strictEqual(A.knight.count,1,'guardian board has exactly one route');
assert.strictEqual(A.knight.solution.length,9,'guardian route contains start plus eight jumps');
assert.deepStrictEqual(A.knight.seals,[[0,4],[0,2],[0,1]],'three seals occur in the specified route order');
assert(A.knight.solution.slice(1).every((p,k)=>L.isKnightMove(A.knight.solution[k],p)),'every guardian move is a legal knight jump');
console.log('Expedition 20 logic: cargo, tidal timing, unique sliding route, unique crate push sequence and knight route passed.');
