'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const root=path.resolve(__dirname,'../..');
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const app=read('expedition10/app.js'),css=read('expedition10/style.css'),sw=read('sw.js');
const pkg=JSON.parse(read('package.json'));
const ctx={self:{}};vm.createContext(ctx);vm.runInContext(read('offline-manifest.js'),ctx);
const offline=ctx.self.MINDLAB_OFFLINE_FILES||[],warm=ctx.self.MINDLAB_JOURNEY_ART||[];
const allOffline=new Set([...offline,...warm]);
const checks=[];const ok=(v,m)=>{assert.ok(v,m);checks.push(m);};
ok(pkg.version==='5.5.28','package is 5.5.28');
ok(sw.includes("const VERSION='5.5.28'"),'service-worker cache is 5.5.28');
ok(app.includes("const SAVE_KEY='mindlab:expedition10:v1'"),'expedition save namespace is unchanged');
ok(!/localStorage\.setItem\(['"]miran:v2/.test(app),'legacy miran:v2 is not written');
const block=app.match(/const expeditionPropFiles=\[([\s\S]*?)\];/);
assert(block,'custom stage prop registry exists');
const propNames=[...block[1].matchAll(/'([^']+\.webp)'/g)].map(m=>m[1]);
ok(propNames.length===24,'exactly 24 custom stage props are registered');
ok(new Set(propNames).size===24,'all 24 stage props are unique');
for(const f of propNames){const p='expedition10/art/props/'+f;ok(fs.existsSync(path.join(root,p)),'custom prop exists: '+f);ok(fs.statSync(path.join(root,p)).size>1000,'custom prop has non-empty image data: '+f);ok(offline.includes(p),'custom prop is precached offline: '+f);}
const details=app.match(/const expeditionArtDetails=\[([\s\S]*?)\];\nstages\.forEach/);
assert(details,'per-stage supporting art registry exists');
const detailPaths=[...details[1].matchAll(/src:'([^']+)'/g)].map(m=>m[1]);
ok(detailPaths.length>=48,'at least two supporting hand-painted elements are assigned to every stage');
for(const p of new Set(detailPaths)){ok(fs.existsSync(path.join(root,p)),'supporting artwork exists: '+p);ok(allOffline.has(p),'supporting artwork is available to offline warming: '+p);}
ok(app.includes("stage.artDetails=expeditionArtDetails[index]"),'art details are bound to every stage record');
ok(app.includes('function artDetailsHtml(st,mode=\'game\')'),'supporting art is rendered in intro and gameplay views');
ok(app.includes('function setHeroinePose(el,mood)')&&app.includes('data-action'),'heroine pose changes trigger a body-action state');
ok(app.includes('lastStoryBeat={from:stages[i].name,text:stages[i].outro,nextIndex:i+1}'),'success stores the next story beat');
ok(app.includes('ex10-story-transition')&&app.includes('ex10-outcome-story'),'story transitions appear between stations and in outcomes');
for(const k of ['ex10-welcome-wave','ex10-thinking-lean','ex10-curious-peek','ex10-worried-shift','ex10-celebrate-bounce'])ok(css.includes('@keyframes '+k),'character body movement exists: '+k);
ok(css.includes('@media(prefers-reduced-motion:reduce)')&&css.includes('animation:none!important'),'reduced-motion disables animated acting');
ok(css.includes('.ex10-art-details')&&css.includes('.ex10-art-detail'),'stage-specific supporting objects have a responsive visual rail');
ok(/aria-live="polite"/.test(app)&&app.includes('aria-label="عناصر مرسومة خاصة باللغز"'),'story and art details are exposed accessibly');
const ids=[...app.matchAll(/id:'(ml10_\d{2})'/g)].map(m=>m[1]);
ok(ids.length===24&&new Set(ids).size===24,'24 active stage identifiers remain intact');
console.log(JSON.stringify({status:'passed',checks:checks.length,version:pkg.version,mainProps:propNames.length,supportingArt:new Set(detailPaths).size,offlineMainProps:propNames.length,storyTransitions:true,bodyMotion:5},null,2));
