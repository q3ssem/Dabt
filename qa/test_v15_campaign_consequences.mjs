import assert from 'node:assert/strict';
import { getCampaignConsequence, resolveAreaConsequence } from '../src/adventures/campaign-consequences.js';
const restore=getCampaignConsequence('restore');
assert.equal(restore.suppressHazards,true);
assert.equal(resolveAreaConsequence({ending:'restore',hazardActive:true,toolCharges:2}).hazardActive,false);
assert.equal(resolveAreaConsequence({ending:'restore',hazardActive:true,toolCharges:2}).changed,true);
const preserve=getCampaignConsequence('preserve');
assert.equal(preserve.suppressHazards,false);
assert.equal(resolveAreaConsequence({ending:'preserve',hazardActive:true,toolCharges:2}).hazardActive,true);
assert.equal(resolveAreaConsequence({ending:'preserve',hazardActive:true,toolCharges:2}).changed,false);
assert.equal(resolveAreaConsequence({ending:null,hazardActive:true,toolCharges:1}).hazardActive,true);
assert.equal(resolveAreaConsequence({ending:'unknown',hazardActive:true,toolCharges:1}).ending,null);
console.log('PASS: branch consequences persist across areas; restore disables hazards while preserve retains the original challenge.');
