import assert from 'node:assert/strict';
import { stepEnemyAI } from '../src/adventures/enemy-ai.js';
assert.equal(stepEnemyAI({state:'patrol',enemyX:100}).state,'patrol');
const heard=stepEnemyAI({state:'patrol',heard:true,heardX:300,heardY:40,enemyX:100});
assert.equal(heard.state,'investigate');assert.deepEqual(heard.lastKnown,{x:300,y:40});
const seen=stepEnemyAI({state:'investigate',visible:true,playerX:500,playerY:60,enemyX:200});
assert.equal(seen.state,'chase');assert.deepEqual(seen.lastKnown,{x:500,y:60});
assert.equal(stepEnemyAI({state:'chase',lastKnown:{x:500,y:60},enemyX:200}).state,'investigate');
assert.equal(stepEnemyAI({state:'telegraph',attackUntil:800,now:500}).state,'telegraph');
assert.equal(stepEnemyAI({state:'telegraph',attackUntil:800,now:801}).state,'recover');
assert.equal(stepEnemyAI({state:'recover',recoverUntil:1000,now:1001,visible:true,playerX:20,enemyX:10}).state,'chase');
assert.equal(stepEnemyAI({state:'search',searchUntil:1500,now:1400}).state,'search');
assert.equal(stepEnemyAI({state:'search',searchUntil:1500,now:1501}).state,'patrol');
console.log('PASS: patrol, sound investigation, sight chase, telegraph, and recovery transitions.');
