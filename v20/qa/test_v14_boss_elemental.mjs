import assert from 'node:assert/strict';
import { resolveBossElement, BOSS_PHASES } from '../src/adventures/boss-elemental.js';
assert.equal(BOSS_PHASES[1].weakness, 'water');
assert.equal(BOSS_PHASES[2].weakness, 'light');
assert.equal(BOSS_PHASES[3].weakness, 'fire');
assert.equal(resolveBossElement({phase:1,element:'light',exposed:true,hp:3}).ok,false);
assert.match(resolveBossElement({phase:1,element:'light',exposed:true,hp:3}).reason,/الماء/);
assert.deepEqual(resolveBossElement({phase:1,element:'water',exposed:true,hp:3}),{ok:true,action:'damage',element:'water',hp:2,defeated:false,nextPhase:2});
assert.equal(resolveBossElement({phase:2,element:'light',exposed:true,hp:2}).hp,1);
assert.equal(resolveBossElement({phase:3,element:'fire',exposed:true,hp:1}).defeated,true);
assert.equal(resolveBossElement({phase:1,element:'water',exposed:false,attackLock:false,hp:3}).ok,false);
const interrupt=resolveBossElement({phase:1,element:'energy',exposed:false,attackLock:true,hp:3});
assert.equal(interrupt.action,'interrupt');
assert.equal(resolveBossElement({phase:1,element:'energy',exposed:false,attackLock:true,energyInterruptUsed:true,hp:3}).ok,false);
assert.equal(resolveBossElement({phase:1,element:'water',exposed:true,hp:0}).ok,false);
console.log('PASS: boss weaknesses, phase progression, timing gate, one-time energy interrupt and defeated guard.');
